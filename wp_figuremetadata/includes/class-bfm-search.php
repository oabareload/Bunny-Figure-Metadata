<?php
/**
 * BFM_Search
 *
 * Integrates figure metadata into standard WordPress frontend searches.
 *
 * Only metadata fields explicitly flagged as 'searchable' participate
 * in searches. Integrates seamlessly with WordPress core search (title,
 * excerpt, content) without duplicate rows, without extra JOINs, and
 * without modifying admin searches.
 *
 * @package BunnyFigureMetadata
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

class BFM_Search {

	/**
	 * Register hooks.
	 *
	 * @return void
	 */
	public function register_hooks(): void {
		add_filter( 'posts_search', array( $this, 'filter_posts_search' ), 20, 2 );
	}

	/**
	 * Filter WordPress core search SQL to include searchable metadata fields.
	 *
	 * Uses an EXISTS subquery on wp_postmeta combined via OR with the standard
	 * content search for each search term.
	 *
	 * @param string   $search Search SQL condition starting with ' AND ...'.
	 * @param WP_Query $query  Current WP_Query instance.
	 * @return string
	 */
	public function filter_posts_search( string $search, $query ): string {
		global $wpdb;

		// 1. Do not touch empty searches or admin searches.
		if ( empty( $search ) || is_admin() ) {
			return $search;
		}

		// 2. Only apply when the query is an actual search.
		if ( ! is_object( $query ) || empty( $query->is_search ) ) {
			return $search;
		}

		// 3. Resolve searchable meta keys.
		$searchable_keys = BFM_Meta_Fields::searchable_keys();
		if ( empty( $searchable_keys ) ) {
			return $search;
		}

		// Prepare escaped list of meta keys for IN (...).
		$escaped_keys = array();
		foreach ( $searchable_keys as $key ) {
			$escaped_keys[] = "'" . esc_sql( $key ) . "'";
		}
		$keys_sql = implode( ', ', $escaped_keys );

		$posts_table    = $wpdb->posts;
		$postmeta_table = $wpdb->postmeta;

		// Target the post_content LIKE clause generated by WordPress core for each term.
		$pattern = '/\(' . preg_quote( $posts_table, '/' ) . '\.post_content\s+LIKE\s+(\'(?:[^\'\\\\]|\\\\.)*\')\)/i';

		$modified = preg_replace_callback(
			$pattern,
			static function ( array $matches ) use ( $posts_table, $postmeta_table, $keys_sql ): string {
				$matched_clause = $matches[0];
				$like_literal   = $matches[1];

				$subquery = "EXISTS (SELECT 1 FROM {$postmeta_table} AS bfm_pm WHERE bfm_pm.post_id = {$posts_table}.ID AND bfm_pm.meta_key IN ({$keys_sql}) AND bfm_pm.meta_value LIKE {$like_literal} AND bfm_pm.meta_value IS NOT NULL AND bfm_pm.meta_value != '')";

				return $matched_clause . ' OR (' . $subquery . ')';
			},
			$search,
			-1,
			$count
		);

		if ( $count > 0 && is_string( $modified ) ) {
			return $modified;
		}

		return $search;
	}
}
